# Generates the certificates used by the TLS tests and writes them, as PEM
# strings, to `test/test_certificates.dart`.
#
# The certificates are embedded in Dart source (rather than loaded from files)
# so that the tests can also run on iOS (see `ios_test/`).
#
# The server certificate satisfies Apple's requirements for TLS server
# certificates (see https://support.apple.com/en-us/103769): a RSA key of at
# least 2048 bits, a SHA-2 signature, the host names in the
# `subjectAltName` extension and an `extendedKeyUsage` of `serverAuth`.
#
# Usage: tool/generate_test_certificates.sh [server_validity_days]

set -euo pipefail

SERVER_DAYS="${1:-825}"
PACKAGE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$PACKAGE_DIR/test/test_certificates.dart"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

make_ca() {
  local name="$1" subject="$2"
  openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 7300 \
    -keyout "$TMP/$name.key" -out "$TMP/$name.pem" \
    -subj "/CN=$subject" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" 2> /dev/null
}

make_ca ca 'cupertino_http Test CA'
make_ca other_ca 'cupertino_http Other Test CA'

openssl req -newkey rsa:2048 -nodes -sha256 \
  -keyout "$TMP/server.key" -out "$TMP/server.csr" \
  -subj '/CN=localhost' 2> /dev/null

cat > "$TMP/server.ext" << 'EOF'
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
subjectAltName=DNS:localhost,IP:127.0.0.1,IP:::1
EOF

openssl x509 -req -in "$TMP/server.csr" \
  -CA "$TMP/ca.pem" -CAkey "$TMP/ca.key" -CAcreateserial \
  -days "$SERVER_DAYS" -sha256 -extfile "$TMP/server.ext" \
  -out "$TMP/server.pem" 2> /dev/null

EXPIRY="$(openssl x509 -in "$TMP/server.pem" -noout -enddate | cut -d= -f2)"

{
  echo "// Copyright (c) 2026, the Dart project authors.  Please see the AUTHORS file"
  echo "// for details. All rights reserved. Use of this source code is governed by a"
  echo "// BSD-style license that can be found in the LICENSE file."
  echo
  echo "// GENERATED by tool/generate_test_certificates.sh. DO NOT EDIT."
  echo "//"
  echo "// The server certificate expires: $EXPIRY."
  echo
  echo "/// A test certificate authority."
  echo "const testCaCertificatePem = '''"
  cat "$TMP/ca.pem"
  echo "''';"
  echo
  echo "/// A certificate authority that did not issue [serverCertificatePem]."
  echo "const otherCaCertificatePem = '''"
  cat "$TMP/other_ca.pem"
  echo "''';"
  echo
  echo "/// A certificate for \`localhost\`, issued by [testCaCertificatePem]."
  echo "const serverCertificatePem = '''"
  cat "$TMP/server.pem"
  echo "''';"
  echo
  echo "/// The private key for [serverCertificatePem]."
  echo "const serverKeyPem = '''"
  cat "$TMP/server.key"
  echo "''';"
} > "$OUT"

echo "Wrote $OUT (server certificate expires $EXPIRY)"
